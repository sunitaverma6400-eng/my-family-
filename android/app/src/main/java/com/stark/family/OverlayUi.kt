                    TextButton(onClick = onStop) { Text("⏹", color = Color(0xFFFF5D5D), fontSize = 20.sp) }
                }
                if (hud.paused) Text("आपने स्क्रीन छुई, इसलिए रुका हूँ। ▶ से जारी रखिए, ⏹ से रोकिए।", color = DIM, fontSize = 12.sp)
